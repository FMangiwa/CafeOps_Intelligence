create table if not exists public.purchase_order_lines (
  purchase_order_line_id text primary key,
  purchase_order_id text not null references public.purchase_orders(purchase_order_id) on delete restrict,
  ingredient_id text not null references public.ingredients(ingredient_id) on delete restrict,
  quantity_ordered numeric(14,4) not null check (quantity_ordered > 0),
  quantity_received numeric(14,4) not null default 0 check (quantity_received >= 0 and quantity_received <= quantity_ordered),
  unit text not null,
  unit_price numeric(12,4) not null check (unit_price >= 0),
