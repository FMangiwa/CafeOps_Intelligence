-- CafeOps Intelligence Project — V1 database schema
-- Target: existing Supabase PostgreSQL project (ap-northeast-1)
-- Synthetic/demo baseline. Review before applying to any production database.
-- Safe to run on a fresh project; uses CREATE TABLE IF NOT EXISTS.
begin;

create extension if not exists pgcrypto;

-- Tenant and access model
create table if not exists public.organizations (
  organization_id text primary key,
  organization_name text not null,
  currency char(3) not null default 'GBP',
  timezone text not null default 'Europe/London',
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now()
);

create table if not exists public.locations (
  location_id text primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  location_name text not null,
  address text,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  unique (organization_id, location_id)
);

create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  role text not null check (role in ('owner','admin','manager','staff','viewer')),
  default_location_id text references public.locations(location_id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.user_location_access (
  user_id uuid not null references public.user_profiles(user_id) on delete cascade,
  location_id text not null references public.locations(location_id) on delete cascade,
  primary key (user_id, location_id)
);

-- Staff and catalog
create table if not exists public.employees (
  employee_id text primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  first_name text not null,
  last_name text not null,
  role text not null,
  hourly_rate numeric(10,2) not null check (hourly_rate >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  menu_item_id text primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  sku text not null,
  menu_item_name text not null,
  category text not null,
  size text not null default 'Standard',
  list_price numeric(12,2) not null check (list_price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (organization_id, sku)
);

create table if not exists public.ingredients (
  ingredient_id text primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  ingredient_name text not null,
  base_unit text not null,
  purchase_pack_size numeric(14,4) not null check (purchase_pack_size > 0),
  purchase_pack_unit text not null,
  latest_pack_cost numeric(12,4) not null check (latest_pack_cost >= 0),
  unit_cost numeric(14,6) not null check (unit_cost >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.recipes (
  recipe_line_id bigint generated by default as identity primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  recipe_id text not null,
  menu_item_id text not null references public.menu_items(menu_item_id) on delete restrict,
  recipe_version integer not null check (recipe_version > 0),
  ingredient_id text not null references public.ingredients(ingredient_id) on delete restrict,
  quantity numeric(14,4) not null check (quantity > 0),
  unit text not null,
  effective_from date not null,
  effective_to date,
  created_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from),
  unique (organization_id, recipe_id, ingredient_id)
