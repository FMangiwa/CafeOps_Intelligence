-- Enable RLS on business tables. Policies below allow authenticated users only
-- when a matching profile and location membership exist. Owners/admins can see
-- all locations in their organization; other roles require explicit location access.
do $$
declare t text;
begin
  foreach t in array array[
    'organizations','locations','user_profiles','user_location_access','employees',
    'menu_items','ingredients','recipes','vendors','vendor_items','purchase_orders',
    'purchase_order_lines','invoices','invoice_lines','sales_transactions','sales_lines',
    'square_sync_state','inventory_balances','inventory_transactions','shifts',
    'labor_records','import_jobs','sync_jobs','metric_definitions'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

-- Helper functions use the authenticated user's profile.
create or replace function public.current_org_id()
returns text language sql stable security definer set search_path = public
as $$ select organization_id from public.user_profiles where user_id = auth.uid() $$;

create or replace function public.can_access_location(p_location_id text)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.user_profiles p
    join public.locations l on l.organization_id = p.organization_id
    where p.user_id = auth.uid()
      and l.location_id = p_location_id
      and (
        p.role in ('owner','admin')
        or exists (select 1 from public.user_location_access a
                   where a.user_id = p.user_id and a.location_id = p_location_id)
      )
  )
$$;

-- Remove/recreate policies idempotently.
-- Apply organization-only policies only to tables that directly contain organization_id.
do $$
declare t text;
begin
  foreach t in array array[
    'locations','employees','menu_items','ingredients','recipes','vendors','vendor_items'
  ] loop
    execute format('drop policy if exists tenant_select on public.%I', t);
    execute format(
      'create policy tenant_select on public.%I
       for select to authenticated
       using (organization_id = public.current_org_id())',
      t
    );
  end loop;
end $$;

-- Tables with both organization_id and location_id.
do $$
declare t text;
begin
  foreach t in array array[
    'purchase_orders','invoices','sales_transactions',
    'square_sync_state','inventory_balances','inventory_transactions',
    'shifts','labor_records','sync_jobs'
  ] loop
    execute format('drop policy if exists tenant_select on public.%I', t);
    execute format(
      'create policy tenant_select on public.%I
       for select to authenticated
       using (
         organization_id = public.current_org_id()
         and public.can_access_location(location_id)
       )',
      t
    );
  end loop;
end $$;

-- Child tables: derive tenant/location access through their parent.
drop policy if exists tenant_select on public.purchase_order_lines;
create policy tenant_select on public.purchase_order_lines
for select to authenticated
using (
  exists (
    select 1
    from public.purchase_orders po
    where po.purchase_order_id = purchase_order_lines.purchase_order_id
      and po.organization_id = public.current_org_id()
      and public.can_access_location(po.location_id)
  )
);

drop policy if exists tenant_select on public.invoice_lines;
create policy tenant_select on public.invoice_lines
for select to authenticated
using (
  exists (
    select 1
    from public.invoices i
    where i.invoice_id = invoice_lines.invoice_id
      and i.organization_id = public.current_org_id()
      and public.can_access_location(i.location_id)
  )
);

drop policy if exists tenant_select on public.sales_lines;
create policy tenant_select on public.sales_lines
for select to authenticated
using (
  exists (
    select 1
    from public.sales_transactions st
    where st.transaction_id = sales_lines.transaction_id
      and st.organization_id = public.current_org_id()
      and public.can_access_location(st.location_id)
  )
);

-- Writes are intentionally server/service-role only for V1. Never expose service-role key.
-- No authenticated INSERT/UPDATE/DELETE policies are created by this migration.

commit;
