create table if not exists public.purchase_orders (
  purchase_order_id text primary key,
  organization_id text not null references public.organizations(organization_id) on delete restrict,
  location_id text not null references public.locations(location_id) on delete restrict,
  vendor_id text not null references public.vendors(vendor_id) on delete restrict,
  order_date date not null,
  expected_date date,
